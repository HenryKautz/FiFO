// Writes examples.js: every problem .pddl under the examples directory with
// its domain and its solution files, as one script the page can load from a
// file:// URL (where it may not read files itself).
//
//   node bundle-examples.js <examples dir> [VARIABLE]  >  examples.js   (see build.sh)
//
// The directory may have subdirectories (clara-examples/ mirrors the CLARA
// tree); each problem is named by its path below the top, e.g.
// "TwoPackage/goals/grid3x3-1-pkg1-p1-3.pddl".
//   - domain: the file whose (define (domain NAME)) matches the problem's
//     (:domain NAME), looked for in the problem's own directory, then in each
//     parent up to the top -- as FiFO looks beside the problem first.  So two
//     directories may each have their own, different domain of one name; two
//     different ones in the SAME directory are an error.
//   - solutions: the non-.pddl files in the problem's directory whose names
//     start with the problem's name followed by "." or "-".
// VARIABLE is the global the script defines (default VIZ_EXAMPLES).

declare const require: any;
declare const process: any;

namespace BundleExamples {
  const fs = require("fs");
  const path = require("path");

  interface File { file: string; text: string }
  const strip = (t: string) => t.replace(/;[^\n]*/g, "");
  const domainName = (t: string) => /\(\s*define\s*\(\s*domain\s+([^\s()]+)/i.exec(strip(t))?.[1]?.toLowerCase();

  //   node bundle-examples.js --domains <pddl dir> > domains.js
  // writes VIZ_DOMAINS: every domain file directly in the directory (FiFO's
  // pddl/ library), with its name, so the page finds a hand-chosen problem's
  // domain by name as FiFO's last resort does.  Two of one name are an error.
  if (process.argv[2] === "--domains") {
    const dir: string = process.argv[3];
    const seen = new Map<string, string>();
    const domains = fs.readdirSync(dir).filter((f: string) => f.endsWith(".pddl")).sort().flatMap((f: string) => {
      const text: string = fs.readFileSync(path.join(dir, f), "utf8");
      const name = domainName(text);
      if (name === undefined) return [];
      if (seen.has(name)) throw new Error(`${dir}: ${seen.get(name)} and ${f} both define domain ${name}`);
      seen.set(name, f);
      return [{ name, file: `${path.basename(dir)}/${f}`, text }];
    });
    process.stdout.write(
      `// Generated by build.sh from FiFO's ${path.basename(dir)}/ -- do not edit; rebuild instead.\n` +
      `var VIZ_DOMAINS = ` + JSON.stringify(domains, null, 1) + ";\n");
    process.exit(0);
  }

  const top: string = process.argv[2];
  const varName: string = process.argv[3] || "VIZ_EXAMPLES";
  const stemOf = (f: string) => f.slice(0, -".pddl".length);
  const matches = (f: string, stem: string) => f.startsWith(stem + ".") || f.startsWith(stem + "-");

  const examples: { problem: File; domain?: File; solutions: File[] }[] = [];
  let undomained = 0;

  /** rel: this directory's path below the top ("" for the top);
   *  outer: the domains of the enclosing directories, innermost first */
  function walk(rel: string, outer: Map<string, File>[]) {
    const dir = path.join(top, rel);
    const names: string[] = fs.readdirSync(dir).filter((f: string) => !f.startsWith(".")).sort();
    const read = (f: string): File => ({ file: rel ? `${rel}/${f}` : f, text: fs.readFileSync(path.join(dir, f), "utf8") });
    const isDir = (f: string) => fs.statSync(path.join(dir, f)).isDirectory();
    const files = names.filter((f) => !isDir(f));
    const pddl = files.filter((f) => f.endsWith(".pddl")).map((f) => ({ name: f, ...read(f) }));
    const here = new Map<string, File>();
    for (const p of pddl) {
      const d = domainName(p.text);
      if (d === undefined) continue;
      const seen = here.get(d);
      if (seen && seen.text !== p.text)
        throw new Error(`two different files in ${dir} define domain ${d}: ${seen.file}, ${p.file}`);
      if (!seen) here.set(d, { file: p.file, text: p.text });
    }
    const scopes = [here, ...outer];
    const problems = pddl.filter((p) => domainName(p.text) === undefined);
    // each solution goes to the problem with the LONGEST matching name, so
    // grid5x5-air.answer belongs to grid5x5-air.pddl, not to grid5x5.pddl too
    const owner = (f: string) => problems.map((p) => stemOf(p.name)).filter((s) => matches(f, s))
      .sort((a, b) => b.length - a.length)[0];
    for (const p of problems) {
      const stem = stemOf(p.name);
      const wants = /\(:domain\s+([^\s()]+)\)/i.exec(strip(p.text))?.[1]?.toLowerCase();
      const domain = wants === undefined ? undefined
        : scopes.map((s) => s.get(wants)).find((d) => d !== undefined);
      if (domain === undefined) undomained++;
      const solutions = files.filter((f) => !f.endsWith(".pddl") && owner(f) === stem).map(read);
      examples.push({ problem: { file: p.file, text: p.text }, domain, solutions });
    }
    for (const sub of names.filter(isDir)) walk(rel ? `${rel}/${sub}` : sub, scopes);
  }
  walk("", []);

  if (undomained > 0)
    process.stderr.write(`bundle-examples: ${undomained} problem(s) under ${top} have no domain file; they load without one\n`);
  process.stdout.write(
    `// Generated by build.sh from ${path.basename(top)}/ -- do not edit; rebuild instead.\n` +
    `var ${varName} = ` + JSON.stringify(examples, null, 1) + ";\n");
}
